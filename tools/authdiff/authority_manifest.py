"""Agent Authority Manifest — declared vs independently observed authority.

Draft ``AUTHORITY.yml`` from inventory; ``verify-manifest`` fails on undeclared
growth. This is **not** a safety certificate — only "matches declaration at
commit X". Publishers may under-declare; scanners must still observe.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from authdiff.inventory.collector import collect_inventory, inventory_to_json
from authdiff.jsonio import write_json
from authdiff.versioning import product_version

MANIFEST_NAME = "AUTHORITY.yml"

_MANIFEST_HEADER = """# Agent Authority Manifest (draft)
# Observed components auto-generated by `authdiff init-manifest`.
# Edit intended_* fields; CI should fail on undeclared authority growth.
# Schema: authdiff.authority_manifest.v1 (see schemas/agent-authority-manifest.schema.json)
# Declared ≠ Configured ≠ Effective ≠ Verified.
schema: authdiff.authority_manifest.v1
product: authdiff
"""


def draft_manifest_from_inventory(inventory: dict[str, Any]) -> str:
    lines = [
        _MANIFEST_HEADER.rstrip(),
        f"product_version: {product_version()}",
        "components:",
    ]
    for comp in inventory.get("components") or []:
        cid = str(comp.get("component_id") or comp.get("name") or "unknown")
        ctype = str(comp.get("type") or "unknown")
        path = str(comp.get("repository_path") or "")
        hints = list(comp.get("priority_hints") or [])
        lines.append(f"  - id: {cid}")
        lines.append(f"    type: {ctype}")
        lines.append(f"    path: {path}")
        lines.append("    authority_layer: CONFIGURED")
        lines.append("    observed_hints:")
        if hints:
            for hint in hints:
                lines.append(f"      - {hint}")
        else:
            lines.append("      - []")
        lines.append("    intended_capabilities: []  # fill: execute_commands, access_network, …")
        lines.append("    intended_destinations: []  # fill: hosts/URLs this may contact")
        lines.append("    human_approval_required: true")
    if not (inventory.get("components") or []):
        lines.append("  []")
    lines.append("policy:")
    lines.append("  fail_on_undeclared: true")
    lines.append("  allow_capability_shrink: true")
    lines.append("limitations:")
    lines.append("  - Matching declaration is not a safety certificate.")
    lines.append("  - Passive observation establishes CONFIGURED authority only.")
    lines.append("")
    return "\n".join(lines)


def init_manifest(target: Path, *, force: bool = False) -> tuple[str, int]:
    dest = target.resolve() / MANIFEST_NAME
    if dest.exists() and not force:
        return f"Exists (use --force): {dest}", 1
    inv = collect_inventory(target)
    body = draft_manifest_from_inventory(inventory_to_json(inv))
    dest.write_text(body, encoding="utf-8")
    return f"Wrote draft {dest} from observed inventory. Edit intended_* before relying on it.", 0


def _parse_declared_ids(text: str) -> set[str]:
    """Minimal YAML-ish id extraction (no PyYAML dependency)."""
    ids: set[str] = set()
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("- id:") or stripped.startswith("id:"):
            ids.add(stripped.split(":", 1)[1].strip())
    return ids


def verify_manifest(target: Path) -> tuple[dict[str, Any], int]:
    root = target.resolve()
    path = root / MANIFEST_NAME
    if not path.is_file():
        return {
            "ok": False,
            "error": f"Missing {MANIFEST_NAME}",
            "hint": "Run `authdiff init-manifest` to draft from observed state.",
        }, 1

    text = path.read_text(encoding="utf-8")
    declared = _parse_declared_ids(text)
    inv = collect_inventory(root)
    observed = inventory_to_json(inv)
    observed_ids = {
        str(c.get("component_id") or c.get("name") or "") for c in observed.get("components") or []
    }
    undeclared = sorted(observed_ids - declared - {""})
    missing = sorted(declared - observed_ids - {""})
    ok = not undeclared  # growth of undeclared authority fails; shrink is advisory
    report = {
        "ok": ok,
        "manifest": str(path),
        "schema": "authdiff.authority_manifest.v1",
        "declared_count": len(declared),
        "observed_count": len(observed_ids),
        "undeclared_components": undeclared,
        "declared_but_missing": missing,
        "verdict": "MATCH" if ok and not missing else ("DRIFT" if ok else "UNDECLARED_AUTHORITY"),
        "limitations": [
            "v1 draft parser is line-oriented; prefer regenerating drafts after large refactors.",
            "Matching declaration ≠ secure — only that observed ids were listed.",
            "Publisher-signed manifests are still untrusted until independently observed.",
        ],
    }
    return report, 0 if ok else 1


def write_verify_report(report: dict[str, Any], output: Path) -> None:
    write_json(output, report)
